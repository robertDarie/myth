import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { World } from './testing/legacy-world.mjs';
import { testWorld } from './testing/kingdom-fixture.mjs';
import { World as ProductionWorld } from './world.mjs';
import { TROOP_TYPES, troopCensus, militaryRoster, trainingOptions } from './troops.mjs';

const catalog = JSON.parse(readFileSync(new URL('../research/parity/fixtures/prototype-troops.json', import.meta.url), 'utf8'));
const fixture = () => { const w = testWorld(), s = w.join('Muster'); const p = w.authenticate(s.token); p.food = p.wood = p.stone = p.gold = p.mana = 8000; return { w, s, p }; };
const order = (w, p, type, targetId, requestId) => w.command(p, { type, targetId, requestId });

test('existing troop costs and stats stay unchanged', () => {
  const live = TROOP_TYPES.map(t => ({ id: t.id, tier: t.tier, role: t.role, health: t.health, damage: t.damage, speed: t.speed, duration: t.duration, cityLevel: t.cityLevel, cost: t.cost }));
  assert.equal(TROOP_TYPES.length, 15);
  assert.deepEqual(JSON.parse(JSON.stringify(live)), catalog.items);
  assert.equal(militaryRoster().siegeAvailable, false);
  assert.equal(militaryRoster().productionClasses, 3);
});

test('a repeated training request does not open a second batch', () => {
  const { w, s, p } = fixture();
  const before = troopCensus(p).total;
  order(w, p, 'train', 'infantry', 'train-oath-0001');
  const food = p.food, queued = p.trainingQueue.length;
  order(w, p, 'train', 'infantry', 'train-oath-0001');
  assert.equal(p.food, food);
  assert.equal(p.trainingQueue.length, queued);
  assert.equal(troopCensus(p).total, before + p.trainingQueue[0].amount);
  assert.throws(() => order(w, p, 'train', 'archers', 'train-oath-0001'), /different/);
  assert.equal(p.food, food);
  const loaded = World.fromSave(w.toSave()), q = loaded.authenticate(s.token);
  const again = q.food;
  order(loaded, q, 'train', 'infantry', 'train-oath-0001');
  assert.equal(q.food, again);
  assert.equal(q.trainingQueue.length, 1);
});

test('siege stays closed and an invalid or unaffordable order changes nothing', () => {
  const { w, p } = fixture();
  const before = troopCensus(p).total;
  assert.throws(() => order(w, p, 'train', 'siege', 'siege-closed-01'), /valid/);
  assert.equal(troopCensus(p).total, before);
  assert.equal(p.trainingReceipts, undefined);
  p.food = 0;
  assert.throws(() => order(w, p, 'train', 'infantry', 'hungry-order-01'), /resources/);
  assert.equal(p.trainingQueue.length, 0);
  assert.equal(p.trainingReceipts, undefined);
  p.food = 8000;
  order(w, p, 'train', 'infantry', 'hungry-order-01');
  assert.equal(p.trainingQueue.length, 1);
  const view = w.snapshot(p.id).players.find(row => row.id === p.id);
  assert.equal(view.militaryRoster.siegeAvailable, false);
  assert.equal(view.militaryRoster.sharedFacility, 'Hall of Spears');
});

test('three queued classes stay independent, cancel refunds once, and promotion keeps the census', () => {
  const { w, p } = fixture();
  w.command(p, { type: 'upgrade' });
  for (let i = 0; i < 800 && p.cityLevel < 2; i++) w.tick(0.1);
  assert.equal(p.cityLevel, 2);
  const before = troopCensus(p).total;
  order(w, p, 'train', 'infantry', 'queue-infantry-01');
  order(w, p, 'train', 'archers', 'queue-archers-001');
  order(w, p, 'train', 'cavalry', 'queue-cavalry-01');
  assert.equal(p.trainingQueue.length, 3);
  assert.equal(troopCensus(p).total, before + p.trainingQueue.reduce((sum, job) => sum + job.amount, 0));
  assert.throws(() => order(w, p, 'train', 'infantry', 'queue-extra-0001'), /full/);
  const food = p.food, job = p.trainingQueue[2];
  w.command(p, { type: 'cancel-job', targetId: job.id });
  assert.equal(p.food, food + job.cost.food);
  assert.equal(p.trainingQueue.length, 2);
  for (let i = 0; i < 400 && p.trainingQueue.length; i++) w.tick(0.1);
  assert.equal(p.trainingQueue.length, 0);
  assert.ok(p.reserveUnits.infantry >= 5);
  assert.ok(p.reserveUnits.archers >= 5);
  const stock = p.food, census = troopCensus(p).total;
  assert.throws(() => order(w, p, 'promote', 'veteranInfantry', 'promote-locked-01'), /Hall of Spears|Research|Citadel/);
  assert.equal(p.food, stock);
  assert.equal(troopCensus(p).total, census);
  assert.equal(p.trainingReceipts.some(row => row.id === 'promote-locked-01'), false);
});

test('reference quotes train each class once, and promotion keeps the count through restart and one refund', () => {
  const w = new ProductionWorld();
  const session = w.join('Muster');
  const p = w.authenticate(session.token);
  const resources = () => ({ food: p.food, wood: p.wood, gold: p.gold, stone: p.stone });
  const census = () => troopCensus(p).total;
  const stock = resources();
  const before = census();
  assert.throws(() => w.command(p, { type: 'train', targetId: 'cavalry', requestId: 'locked-cavalry-1' }), /Citadel level 2/);
  assert.throws(() => w.command(p, { type: 'train', targetId: 'veteranInfantry', requestId: 'locked-veteran-1' }), /Citadel level 2/);
  assert.throws(() => w.command(p, { type: 'train', targetId: 'siege', requestId: 'siege-refused-01' }), /valid troop/);
  p.food = 0;
  assert.throws(() => w.command(p, { type: 'train', targetId: 'infantry', requestId: 'broke-train-001' }), /Not enough resources/);
  p.food = stock.food;
  assert.deepEqual(resources(), stock);
  assert.equal(p.trainingQueue.length, 0);
  assert.equal(p.trainingReceipts, undefined);
  assert.equal(census(), before);
  const tierOne = trainingOptions(p).filter(t => t.tier === 1);
  assert.deepEqual(tierOne.map(t => t.id), ['infantry', 'archers', 'cavalry']);
  assert.equal(tierOne.find(t => t.id === 'cavalry').lockedReason, 'Citadel level 2 required.');
  assert.equal(tierOne.every(t => t.orderAmount === 100), true);
  w.command(p, { type: 'upgrade' });
  for (let i = 0; i < 300 && p.cityLevel < 2; i++) w.tick(0.1);
  assert.equal(p.cityLevel, 2);
  assert.equal(trainingOptions(p).find(t => t.id === 'cavalry').lockedReason, '');
  assert.equal(trainingOptions(p).find(t => t.id === 'veteranInfantry').lockedReason, 'Hall of Spears level 2 required.');
  p.food = p.wood = 100000;
  for (const id of ['infantry', 'archers', 'cavalry']) {
    const quote = trainingOptions(p).find(t => t.id === id);
    const paid = resources();
    w.command(p, { type: 'train', targetId: id, requestId: 'ref-' + id + '-01' });
    const job = p.trainingQueue.at(-1);
    assert.equal(job.amount, quote.orderAmount);
    assert.deepEqual(job.cost, quote.orderCost);
    assert.equal(job.duration, quote.orderSeconds);
    assert.equal(p.food, paid.food - (quote.orderCost.food ?? 0));
    assert.equal(p.wood, paid.wood - (quote.orderCost.wood ?? 0));
  }
  assert.equal(p.trainingQueue.length, 3);
  assert.equal(census(), before + 300);
  const blocked = resources();
  assert.throws(() => w.command(p, { type: 'train', targetId: 'infantry', requestId: 'ref-fourth-001' }), /three orders/);
  assert.deepEqual(resources(), blocked);
  assert.equal(p.trainingReceipts.some(row => row.id === 'ref-fourth-001'), false);
  w.command(p, { type: 'train', targetId: 'infantry', requestId: 'ref-infantry-01' });
  assert.throws(() => w.command(p, { type: 'train', targetId: 'archers', requestId: 'ref-infantry-01' }), /different/);
  assert.deepEqual(resources(), blocked);
  const loaded = ProductionWorld.fromSave(structuredClone(w.toSave()));
  const q = loaded.authenticate(session.token);
  loaded.command(q, { type: 'train', targetId: 'infantry', requestId: 'ref-infantry-01' });
  assert.equal(q.trainingQueue.length, 3);
  assert.throws(() => loaded.command(q, { type: 'train', targetId: 'cavalry', requestId: 'ref-infantry-01' }), /different/);
  const head = q.trainingQueue[0];
  loaded.cityTick(q, head.duration);
  assert.equal(q.trainingQueue.length, 2);
  assert.equal(q.reserveUnits.infantry, 100);
  assert.equal(troopCensus(q).total, before + 300);
  loaded.cityTick(q, 1);
  assert.equal(q.reserveUnits.infantry, 100);
  assert.equal(q.trainingQueue[0].targetId, 'archers');
  const cancel = q.trainingQueue.find(job => job.targetId === 'cavalry');
  const refundFood = q.food, refundWood = q.wood;
  loaded.command(q, { type: 'cancel-job', targetId: cancel.id });
  assert.equal(q.food, refundFood + cancel.cost.food);
  assert.equal(q.wood, refundWood + cancel.cost.wood);
  assert.equal(q.trainingQueue.some(job => job.id === cancel.id), false);
  assert.throws(() => loaded.command(q, { type: 'cancel-job', targetId: cancel.id }));
  assert.equal(q.food, refundFood + cancel.cost.food);
  assert.equal(q.reserveUnits.infantry, 100);
  while (p.trainingQueue.length) w.command(p, { type: 'cancel-job', targetId: p.trainingQueue.at(-1).id });
  p.buildings.barracks = 2; p.buildings.academy = 2; p.technologies.drill = 1; p.technologies.veterans = 1;
  p.reserveTroops = 100; p.reserveUnits = { infantry: 100, archers: 0, cavalry: 0 };
  const quote = trainingOptions(p).find(t => t.id === 'veteranInfantry');
  assert.equal(quote.lockedReason, '');
  assert.equal(quote.promotionAmount, 100);
  const owned = census();
  const paid = resources();
  w.command(p, { type: 'promote', targetId: 'veteranInfantry', requestId: 'promote-oath-01' });
  const job = p.trainingQueue.find(row => row.type === 'promote');
  assert.deepEqual(job.cost, quote.promotionCost);
  assert.equal(job.duration, quote.promotionSeconds);
  assert.equal(job.amount, 100);
  assert.equal(p.reserveUnits.infantry, 0);
  assert.equal(census(), owned);
  assert.equal(p.food, paid.food - quote.promotionCost.food);
  assert.equal(p.wood, paid.wood - quote.promotionCost.wood);
  w.command(p, { type: 'promote', targetId: 'veteranInfantry', requestId: 'promote-oath-01' });
  assert.equal(p.food, paid.food - quote.promotionCost.food);
  assert.throws(() => w.command(p, { type: 'promote', targetId: 'veteranArchers', requestId: 'promote-oath-01' }), /different/);
  const promoted = ProductionWorld.fromSave(structuredClone(w.toSave()));
  const veteran = promoted.authenticate(session.token);
  promoted.command(veteran, { type: 'promote', targetId: 'veteranInfantry', requestId: 'promote-oath-01' });
  assert.equal(veteran.trainingQueue.filter(row => row.type === 'promote').length, 1);
  const kept = troopCensus(veteran).total;
  promoted.cityTick(veteran, veteran.trainingQueue.find(row => row.type === 'promote').duration);
  assert.equal(veteran.reserveUnits.veteranInfantry, 100);
  assert.equal(veteran.reserveUnits.infantry, 0);
  assert.equal(troopCensus(veteran).total, kept);
  promoted.cityTick(veteran, 5);
  assert.equal(veteran.reserveUnits.veteranInfantry, 100);
  const refunded = ProductionWorld.fromSave(structuredClone(w.toSave()));
  const restored = refunded.authenticate(session.token);
  const promotion = restored.trainingQueue.find(row => row.type === 'promote');
  const backFood = restored.food, backWood = restored.wood;
  refunded.command(restored, { type: 'cancel-job', targetId: promotion.id });
  assert.equal(restored.reserveUnits.infantry, 100);
  assert.equal(restored.reserveUnits.veteranInfantry, undefined);
  assert.equal(restored.food, backFood + promotion.cost.food);
  assert.equal(restored.wood, backWood + promotion.cost.wood);
  assert.throws(() => refunded.command(restored, { type: 'cancel-job', targetId: promotion.id }));
  assert.equal(restored.food, backFood + promotion.cost.food);
  assert.equal(troopCensus(restored).total, kept);
});
