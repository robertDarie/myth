import test from 'node:test';
import assert from 'node:assert/strict';
import { testWorld } from './testing/kingdom-fixture.mjs';
import { World } from './world.mjs';
import { scoutProfile, SCOUT_CAMP_LEVELS } from './scout-camp.mjs';
import { cellIndex } from './exploration.mjs';
const setup = (names = ['Pathfinder', 'Neighbor']) => {
  const w = testWorld(), sessions = names.map(name => w.join(name));
  return { w, sessions, players: sessions.map(s => w.authenticate(s.token)) };
};
const advance = (w, seconds) => { for (let i = 0; i < seconds * 10; i++) w.tick(0.1); };
const travel = level => {
  const { w, players: [p] } = setup(['Runner']);
  p.buildings.scoutcamp = level;
  w.command(p, { type: 'scout-send', x: p.homeX + 20, z: p.homeZ });
  advance(w, 1);
  return Math.hypot(p.scouts[0].x - p.homeX, p.scouts[0].z - p.homeZ);
};
const exploredBy = level => {
  const { w, players: [p] } = setup(['Surveyor']);
  const before = p.explored.length;
  p.buildings.scoutcamp = level;
  w.command(p, { type: 'scout-send', x: 24, z: 24 });
  advance(w, 16);
  return p.explored.length - before;
};

test('explored land stays discovered after the scout leaves, alliance changes and reload', () => {
  const { w, sessions, players: [p, ally] } = setup();
  const before = [...p.explored];
  w.command(p, { type: 'scout-send', x: 24, z: 24 });
  advance(w, 12);
  assert.equal(p.scouts.length, 0);
  assert.ok(p.explored.length > before.length);
  const settled = [...p.explored];
  advance(w, 20);
  assert.deepEqual(p.explored, settled);
  w.command(p, { type: 'alliance-create', name: 'Watchers' });
  w.command(ally, { type: 'alliance-join', targetId: p.allianceId });
  advance(w, 1);
  for (const cell of settled) assert.ok(p.explored.includes(cell));
  w.command(ally, { type: 'alliance-leave' });
  for (const cell of settled) assert.ok(p.explored.includes(cell));
  const restored = World.fromSave(w.toSave()), q = restored.authenticate(sessions[0].token);
  assert.equal(restored.toSave().schema, 16);
  assert.deepEqual(q.explored, p.explored);
  assert.equal(q.buildings.scoutcamp, 1);
  advance(restored, 10);
  assert.deepEqual(q.explored, p.explored);
});

test('schema 15 scouts and missing camps migrate without erasing exploration', () => {
  const { w, sessions, players: [p] } = setup(['Legacy']);
  p.explored = [4, 8, 12];
  const save = w.toSave();
  save.schema = 15;
  const legacy = save.world.players[0];
  legacy.explored = [4, 8, 12];
  legacy.scout = { id: 'legacy-scout', ownerId: legacy.id, x: legacy.homeX, z: legacy.homeZ, homeX: legacy.homeX, homeZ: legacy.homeZ, targetX: 22, targetZ: 22, phase: 'Outbound' };
  delete legacy.scouts; delete legacy.autoExplore; delete legacy.buildings.scoutcamp;
  const restored = World.fromSave(save), q = restored.authenticate(sessions[0].token);
  assert.equal(restored.toSave().schema, 16);
  assert.deepEqual(q.explored.filter(cell => [4, 8, 12].includes(cell)), [4, 8, 12]);
  assert.equal(q.buildings.scoutcamp, 1);
  assert.equal(q.scouts.length, 1);
  assert.equal(q.scouts[0].id, 'legacy-scout');
  assert.equal(q.scouts[0].phase, 'Outbound');
  assert.equal(q.scout, undefined);
  assert.equal(q.autoExplore, false);
});

test('Outlook of the Horizon levels change capacity, speed and reveal using the documented table', () => {
  assert.deepEqual(SCOUT_CAMP_LEVELS.map(row => row.scouts), [0, 1, 1, 2, 2, 3]);
  assert.equal(scoutProfile(1).speed, 7);
  assert.equal(scoutProfile(1).radius, 9);
  assert.equal(scoutProfile(5).speed, 13);
  assert.equal(scoutProfile(5).radius, 15);
  const { w, players: [p] } = setup(['Builder']);
  p.cityLevel = 2; p.wood = p.food = p.gold = 10000;
  const card = w.snapshot(p.id).players.find(a => a.id === p.id).cityBuildings.find(b => b.id === 'scoutcamp');
  assert.equal(card.name, 'Outlook of the Horizon');
  assert.equal(card.level, 1);
  assert.equal(card.scoutCamp.scouts, 1);
  assert.equal(card.scoutCamp.hasNext, true);
  assert.ok(card.scoutCamp.nextSpeed > card.scoutCamp.speed);
  assert.ok(card.nextCost.wood > 0 && card.nextDuration > 0);
  w.command(p, { type: 'building-upgrade', targetId: 'scoutcamp' });
  assert.equal(p.buildings.scoutcamp, 1);
  advance(w, card.nextDuration + 0.2);
  assert.equal(p.buildings.scoutcamp, 2);
  assert.equal(w.snapshot(p.id).exploration.scoutCamp.speed, 8.5);
  assert.ok(Math.abs(travel(1) - 7) < 0.05);
  assert.ok(Math.abs(travel(5) - 13) < 0.05);
  assert.ok(exploredBy(5) > exploredBy(1));
  p.buildings.scoutcamp = 3;
  w.command(p, { type: 'scout-send', x: 20, z: 20 });
  assert.throws(() => w.command(p, { type: 'scout-send', x: 20, z: 21 }), /region/);
  w.command(p, { type: 'scout-send', x: 28, z: 20 });
  assert.equal(p.scouts.length, 2);
  assert.throws(() => w.command(p, { type: 'scout-send', x: 30, z: 30 }), /deployed/);
  p.buildings.scoutcamp = 5;
  w.command(p, { type: 'scout-send', x: 24, z: 28 });
  assert.equal(p.scouts.length, 3);
});

test('auto explore, redirect and recall stay server-owned and do not repeat discovery rewards', () => {
  const { w, players: [p] } = setup(['Auto']);
  const known = new Set(p.explored);
  w.command(p, { type: 'scout-auto', enabled: true });
  assert.equal(p.autoExplore, true);
  assert.equal(p.scouts.length, 1);
  assert.equal(p.scouts[0].phase, 'Outbound');
  assert.equal(known.has(cellIndex({ x: p.scouts[0].targetX, z: p.scouts[0].targetZ })), false);
  const origin = cellIndex({ x: p.homeX, z: p.homeZ });
  const target = cellIndex({ x: p.scouts[0].targetX, z: p.scouts[0].targetZ });
  assert.ok(Math.max(Math.abs(target % 20 - origin % 20), Math.abs(Math.floor(target / 20) - Math.floor(origin / 20))) <= scoutProfile(1).autoSectors);
  w.command(p, { type: 'scout-auto', enabled: false });
  w.command(p, { type: 'scout-recall', targetId: p.scouts[0].id });
  advance(w, 8);
  assert.equal(p.scouts.length, 0);
  assert.equal(p.journey.metrics.surveys, 0);
  w.command(p, { type: 'scout-send', x: 30, z: 30 });
  advance(w, 1);
  const departed = p.scouts[0].x;
  w.command(p, { type: 'scout-redirect', targetId: p.scouts[0].id, x: 16, z: 16 });
  assert.equal(p.scouts[0].phase, 'Outbound');
  assert.equal(p.scouts[0].targetX, 16);
  advance(w, 0.4);
  assert.ok(Math.hypot(p.scouts[0].x - p.homeX, p.scouts[0].z - p.homeZ) > 1);
  assert.notEqual(p.scouts[0].x, departed);
  advance(w, 8);
  assert.equal(p.scoutReports.length, 1);
  assert.ok(Math.hypot(p.scoutReports[0].x - 16, p.scoutReports[0].z - 16) < 1);
  const surveys = p.journey.metrics.surveys;
  w.command(p, { type: 'scout-send', x: 16, z: 16 });
  advance(w, 10);
  assert.equal(p.journey.metrics.surveys, surveys);
  assert.equal(p.scoutReports.length, 2);
  for (const destination of [{ x: 0, z: 20 }, { x: 80, z: 20 }, { x: 20, z: 0 }, { x: Number.NaN, z: 20 }]) assert.throws(() => w.command(p, { type: 'scout-send', ...destination }), /inside the map/);
});

test('players cannot read or command another city scout, and explored land does not reveal enemy troops', () => {
  const { w, players: [p, enemy] } = setup();
  enemy.x = 30; enemy.z = 25; enemy.troops = 40;
  w.command(p, { type: 'scout-send', x: 30, z: 25 });
  advance(w, 1);
  assert.throws(() => w.command(enemy, { type: 'scout-recall', targetId: p.scouts[0].id }), /no longer/);
  assert.throws(() => w.command(enemy, { type: 'scout-redirect', targetId: p.scouts[0].id, x: 18, z: 18 }), /no longer/);
  advance(w, 12);
  assert.ok(p.explored.includes(cellIndex({ x: 30, z: 25 })));
  const own = w.snapshot(p.id), hidden = w.snapshot(enemy.id);
  assert.equal(own.armies.some(a => a.id === enemy.id), false);
  assert.equal(own.exploration.reports.length, 1);
  assert.equal(hidden.exploration.reports.length, 0);
  assert.equal(hidden.players.find(a => a.id === p.id).explored, undefined);
  assert.equal(hidden.players.find(a => a.id === p.id).scouts, undefined);
  assert.equal(own.players.find(a => a.id === p.id).explored, undefined);
  assert.ok(p.explored.some(cell => !hidden.exploration.explored.includes(cell)));
});

test('two cities auto-explore, redirect and recall without mixing orders or private reports', () => {
  const { w, players: [a, b] } = setup(['Alpha', 'Beta']);
  a.buildings.scoutcamp = 5; b.buildings.scoutcamp = 5;
  const aLand = a.explored.length, bLand = b.explored.length;
  w.command(a, { type: 'scout-auto', enabled: true });
  w.command(b, { type: 'scout-auto', enabled: true });
  assert.ok(a.scouts.length > 0 && b.scouts.length > 0);
  assert.ok(a.scouts.every(s => s.ownerId === a.id) && b.scouts.every(s => s.ownerId === b.id));
  assert.equal(new Set([...a.scouts, ...b.scouts].map(s => s.id)).size, a.scouts.length + b.scouts.length);
  const redirected = a.scouts[0].id;
  w.command(a, { type: 'scout-redirect', targetId: redirected, x: 36, z: 16 });
  assert.equal(a.scouts[0].targetX, 36); assert.equal(a.scouts[0].targetZ, 16); assert.equal(a.scouts[0].phase, 'Outbound');
  assert.throws(() => w.command(b, { type: 'scout-redirect', targetId: a.scouts[0].id, x: 28, z: 16 }), /no longer/);
  assert.throws(() => w.command(a, { type: 'scout-recall', targetId: b.scouts[0].id }), /no longer/);
  advance(w, 1);
  const recalled = b.scouts[0];
  const away = Math.hypot(recalled.x - b.homeX, recalled.z - b.homeZ);
  w.command(b, { type: 'scout-recall', targetId: recalled.id });
  const returning = b.scouts.find(s => s.id === recalled.id);
  if (away > 0.2) { assert.ok(returning); assert.equal(returning.phase, 'Returning'); assert.equal(returning.rewardPending, false); }
  else assert.equal(returning, undefined);
  assert.equal(a.scouts.find(s => s.id === redirected).targetX, 36);
  assert.equal(a.autoExplore, true); assert.equal(b.autoExplore, true);
  advance(w, 2);
  assert.ok(a.explored.length >= aLand && b.explored.length >= bLand);
  const own = w.snapshot(a.id), other = w.snapshot(b.id);
  assert.ok((own.exploration.reports ?? []).every(r => !(other.exploration.reports ?? []).some(x => x.id === r.id)));
  assert.equal(own.players.find(p => p.id === b.id).scouts, undefined);
});
